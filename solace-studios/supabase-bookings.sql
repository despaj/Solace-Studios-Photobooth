create table public.bookings (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  event_type text not null,
  event_date timestamptz not null,
  event_location text not null,
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'declined', 'completed')),
  created_at timestamptz not null default now()
);

-- Keep Row Level Security enabled. The browser does not access this table directly;
-- the Vercel API uses the service-role key stored only in Vercel environment variables.
alter table public.bookings enable row level security;
